def test_head_base_joriy_til_va_qamrov(tmp_path):
    st = MeetingStore(tmp_path / "m")
    m = _meeting(st)
    old_rev = _row(st, m, "uz-cyrl", 900, rev=2)                       # qator tahriridan oldin - o'sha avlod
    ru = _row(st, m, "ru", 800)
    _row(st, m, "en", 700, gen=1)                                      # qayta o'girilishdan oldingi avlod
    _row(st, m, "en", 650, gen=None)                                   # v8 dan oldingi eski versiya - avlod noma'lum
    _row(st, m, "uz-cyrl", 600, status="failed", error="llm_busy")
    assert rows.ready_row(st, m["id"], "uz-cyrl", 3) is None           # HEAD - joriy versiyada tayyori yo'q
    assert rows.ready_row(st, m["id"], "ru", 3)["id"] == ru
    assert rows.base_row(st, m, "uz-cyrl") == (st.minutes_row(m["id"], old_rev), None)
    assert rows.base_row(st, m, "en") == (None, "minutes_outdated")
    assert rows.base_row(st, m, "uz-latn") == (None, "minutes_missing")
    assert rows.current_lang(st, m) == "ru"
    # Prompt versiyalari: minutes-2 ham joriy (deploydan keyin qayta yozilmaydi), minutes-1 - yo'q.
    legacy = _row(st, m, "uz-latn", 500, version="minutes-2")
    assert rows.ready_row(st, m["id"], "uz-latn", 3)["id"] == legacy
    _row(st, m, "uz-latn", 400, version="minutes-1")
    assert rows.ready_row(st, m["id"], "uz-latn", 3)["id"] == legacy and rows.current_lang(st, m) == "uz-latn"
    # Ko'rsatmalar qamrovi: hujjat yozilganda berilganlari (kesilganlari ham) - qo'llangan.
    covered = st.minutes_row(m["id"], _row(st, m, "ru", 300, notes=[{"id": "n1", "text": "…"}, {"x": 1}]))
    assert rows.snapshot(covered) == [{"id": "n1", "text": "…"}] and rows.applied_ids(covered) == {"n1"}
    assert rows.pending(covered, [{"id": "n1"}, {"id": "n2"}]) == [{"id": "n2"}]
    assert rows.snapshot(None) == [] and rows.snapshot({"guidance_json": "[]"}) == []
    # Tiriklik: `running` va eskirmagan; ombor o'zgarmaydi.
    fresh = {"status": "running", "created_at": NOW - 10}
    assert rows.is_live(fresh, NOW) and not rows.is_live({**fresh, "status": "ready"}, NOW)
    assert not rows.is_live({**fresh, "created_at": NOW - rows.stale_after() - 1}, NOW)
    st.close_all()


