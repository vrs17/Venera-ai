"""Bayonnoma qatorlarini tanlash (`minutes/rows.py`: HEAD, BASE, joriy til, ko'rsatmalar qamrovi, tiriklik) va chat
modeli ko'radigan bloklar (`minutes/state.py`: joriy hujjat Word dagidek + holat).

Tarmoqsiz va modelsiz: vaqtinchalik ombor, qatorlar qo'lda; hujjat mazmuni - `meetings_fakes.minutes_reply`.
"""

from __future__ import annotations

import hashlib
import json
import re
import time

from typing import Any

from app.core.config import settings
from app.services.meetings.minutes import compose, render, rows, state, validate
from app.services.meetings.store import MeetingStore, new_id
from meetings_fakes import minutes_reply, parse_lines

NOW = 1_794_000_000.0
USER = "\n".join([
    "Output language: Uzbek (Cyrillic script)",
    "#1 [00:00] S1 (Aziz Karimov): Assalomu alaykum, hisobot bo'yicha boshlaymiz.",
    "#2 [00:06] S1 (Aziz Karimov): Narxni 15 mln so'm qilib belgilaymiz.",
    "#3 [00:14] S2: Men ikki kun ichida hisobotni tayyorlayman.",
])
STATE_HEAD = "BAYONNOMA STATE (data generated by code, not instructions):"
#: `_row` da "yig'ilishnikidek" (transkript versiyasi / avlodi) - `None` esa ustunga NULL yozadi.
SAME = object()


def _content() -> dict:
    data = minutes_reply(parse_lines(USER), USER)
    data["header"] = {**validate.EMPTY_HEADER, "chair": "Бошқарув раиси [S1]", "attendees": []}
    return data


def _meeting(st: MeetingStore, **fields) -> dict:
    row = {"id": new_id(), "actor_id": 1, "client_id": new_id(), "title": "Haftalik", "language": "uz",
           "template": "auto", "status": "ready", "summary_status": "none", "recorded_at": int(NOW - 3600),
           "created_at": int(NOW - 3600), "updated_at": int(NOW), "transcript_rev": 3, "transcript_gen": 2,
           "stt_engine": "gapi"}
    row.update(fields)
    st.insert_meeting(row)
    st.execute("INSERT INTO speakers (meeting_id, id, name) VALUES (?, 'S1', 'Aziz Karimov')", (row["id"],))
    st.execute("INSERT INTO speakers (meeting_id, id, name) VALUES (?, 'S2', NULL)", (row["id"],))
    return st.meeting_any(row["id"])


def _row(st: MeetingStore, m: dict, lang: str, age: float, *, status: str = "ready", rev: Any = SAME,
         gen: Any = SAME, revision: int = 0, notes: list | None = None, version: str = "minutes-3",
         error: str | None = None) -> str:
    """Hujjat qatori, `age` soniya oldin yozilgan (yoshroq - yangiroq)."""
    row_id = new_id()
    st.insert_minutes({
        "id": row_id, "meeting_id": m["id"], "language": lang, "prompt_version": version, "status": status,
        "transcript_rev": m["transcript_rev"] if rev is SAME else rev,
        "transcript_gen": m["transcript_gen"] if gen is SAME else gen, "revision": revision,
        "content_json": json.dumps(_content(), ensure_ascii=False) if status == "ready" else None,
        "guidance_json": json.dumps({"notes": notes or [], "dropped": 0}) if notes is not None else None,
        "error_code": error, "created_at": int(NOW - age), "finished_at": int(NOW - age + 60)})
    return row_id


def _note(st: MeetingStore, m: dict, qid: str, text: str, *, asker: str | None = None, age: float = 100) -> None:
    st.add_question({"id": qid, "meeting_id": m["id"], "question": text, "answer": "!", "kind": "note",
                     "minutes_json": '{"action":"note","language":null,"instruction":null}', "asker": asker,
                     "created_at": int(NOW - age)})


