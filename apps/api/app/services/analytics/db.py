def _migrate(conn: sqlite3.Connection) -> int:
    """Sxemani oxirgi versiyaga yetkazadi; yakuniy versiyani qaytaradi.

    Har qadam O'Z TRANZAKSIYASIDA, `BEGIN IMMEDIATE` bilan: yozuv qulfi
    olingandan KEYIN versiya qayta o'qiladi. Ikki jarayon (API va
    `tools/seed_analytics.py`) bir vaqtda ochsa, ikkinchisi birinchisi
    tugashini kutadi va qadamni takrorlamaydi. SQLite'da DDL ham, `PRAGMA
    user_version` ham tranzaksiyaga bo'ysunadi - yarim bajarilgan qadam
    qolmaydi.
    """
    version = conn.execute("PRAGMA user_version").fetchone()[0]
    if version > SCHEMA_VERSION:
        # Fayl KELAJAKDAGI kod bilan yangilangan (masalan eski versiyaga
        # qaytarilgan deploy). Tushirib bo'lmaydi; mavjud jadvallar bilan
        # ishlashga harakat qilamiz - yangi ustunlar faqat qo'shiladi.
        log.warning("Analitika ombori yangiroq sxemada: %d > %d", version, SCHEMA_VERSION)
        return version
    while version < SCHEMA_VERSION:
        conn.execute("BEGIN IMMEDIATE")
        try:
            version = conn.execute("PRAGMA user_version").fetchone()[0]
            if version >= SCHEMA_VERSION:
                conn.execute("COMMIT")
                break
            for statement in MIGRATIONS[version]:
                conn.execute(statement)
            version += 1
            # PRAGMA parametr qabul qilmaydi; `version` - bizning butun son.
            conn.execute(f"PRAGMA user_version = {int(version)}")
            conn.execute("COMMIT")
        except BaseException:
            with contextlib.suppress(sqlite3.Error):
                conn.execute("ROLLBACK")
            raise
        log.info("Analitika ombori sxemasi: v%d", version)
    return version


