class Database:
    """Bitta SQLite fayl. Har ip o'z ulanishini oladi (`connect`).

    O'QISH to'g'ridan-to'g'ri (`rows`, `row`, `scalar`). YOZISH so'rov
    yo'llarida `writer.py` orqali (navbat, bitta ip). Admin amallari kabi
    natijasi DARHOL kerak bo'lgan kam sonli yozuvlar uchun `transaction()`
    bor - WAL va `busy_timeout` bilan ular yozuvchi ip bilan to'qnashmaydi,
    faqat navbat kutadi.
    """

    def __init__(self, path: Path | str) -> None:
        self.path = Path(path)
        self._local = threading.local()
        self._lock = threading.Lock()
        self._migrated = False
        self._prepared = False
        #: Barcha ochilgan ulanishlar - `close_all` uchun (testlar, to'xtash).
        self._all: set[sqlite3.Connection] = set()

    def __repr__(self) -> str:
        return f"Database({str(self.path)!r})"

    # --- ulanish ---

    def connect(self) -> sqlite3.Connection:
        """Joriy ipning ulanishi; birinchi chaqiruvda ochiladi va sxema
        tekshiriladi.

        `isolation_level=None` - avtokommit: Python'ning yashirin `BEGIN` i
        yo'q, tranzaksiya faqat ochiq yozilganda (`transaction()`, yozuvchi
        ip). Yashirin tranzaksiya o'qiydigan ipda ochiq qolib, WAL
        checkpoint'ini to'xtatib qo'yishi mumkin edi.
        """
        conn = getattr(self._local, "conn", None)
        if conn is not None:
            return conn
        self._prepare()
        conn = sqlite3.connect(
            str(self.path),
            timeout=5.0,
            isolation_level=None,
            # Ulanish baribir FAQAT o'z ipida ishlatiladi; bu bayroq faqat
            # `close_all` boshqa ipdan yopa olishi uchun.
            check_same_thread=False,
        )
        try:
            conn.row_factory = sqlite3.Row
            with contextlib.suppress(sqlite3.OperationalError):
                # Faqat o'qiladigan diskda WAL yoqilmaydi - o'qish baribir ishlasin.
                conn.execute("PRAGMA journal_mode=WAL")
            conn.execute("PRAGMA synchronous=NORMAL")
            conn.execute("PRAGMA busy_timeout=5000")
            conn.execute("PRAGMA foreign_keys=ON")
            with self._lock:
                if not self._migrated:
                    _migrate(conn)
                    self._migrated = True
        except BaseException:
            conn.close()
            raise
        self._local.conn = conn
        with self._lock:
            self._all.add(conn)
        return conn

    def _prepare(self) -> None:
        """Papka 700, fayl 600 - bir marta.

        Papka FAQAT O'ZIMIZ yaratgan yoki egasi biz bo'lgan va "sticky"
        bo'lmagan bo'lsa toraytiriladi: yo'l adashib `/tmp` kabi umumiy
        papkaga qo'yilsa, uning huquqlarini buzib qo'ymaslik kerak.

        Fayl SQLite ochishidan OLDIN 600 bilan yaratiladi - aks holda u
        `umask` bo'yicha (odatda 644, ya'ni hamma o'qiy oladi) paydo bo'lib,
        bir lahza ochiq turardi. `-wal` va `-shm` fayllari huquqni asosiy
        fayldan oladi.
        """
        if self._prepared:
            return
        with self._lock:
            if self._prepared:
                return
            parent = self.path.parent
            created = not parent.exists()
            parent.mkdir(parents=True, exist_ok=True)
            with contextlib.suppress(OSError):
                info = parent.stat()
                owned = info.st_uid == os.getuid()
                if created or (owned and not info.st_mode & stat.S_ISVTX):
                    os.chmod(parent, 0o700)
            if not self.path.exists():
                fd = os.open(self.path, os.O_CREAT | os.O_WRONLY, 0o600)
                os.close(fd)
            with contextlib.suppress(OSError):
                if self.path.stat().st_uid == os.getuid():
                    os.chmod(self.path, 0o600)
            self._prepared = True

    def close(self) -> None:
        """Joriy ipning ulanishini yopadi."""
        conn = getattr(self._local, "conn", None)
        if conn is None:
            return
        self._local.conn = None
        with self._lock:
            self._all.discard(conn)
        with contextlib.suppress(sqlite3.Error):
            conn.close()

    def close_all(self) -> None:
        """HAMMA iplarning ulanishlarini yopadi - faqat to'xtash va testlar
        uchun, ya'ni hech kim ulardan foydalanmayotgan paytda."""
        with self._lock:
            conns, self._all = list(self._all), set()
        for conn in conns:
            with contextlib.suppress(sqlite3.Error):
                conn.close()
        # Boshqa iplarning `threading.local` ini tozalab bo'lmaydi; yopilgan
        # ulanishni ular keyingi `connect()` da sezmasin deb yangi obyekt.
        self._local = threading.local()

    # --- o'qish ---

    def execute(self, sql: str, params: Params = ()) -> sqlite3.Cursor:
        """Bitta so'rov (avtokommit). Yozish uchun - faqat natija darhol
        kerak bo'lsa; aks holda `writer.get_writer().submit`."""
        return self.connect().execute(sql, params)

    def rows(self, sql: str, params: Params = ()) -> list[dict[str, Any]]:
        """Hamma qatorlar lug'at ko'rinishida."""
        return [dict(r) for r in self.connect().execute(sql, params).fetchall()]

    def row(self, sql: str, params: Params = ()) -> dict[str, Any] | None:
        """Birinchi qator yoki `None`."""
        found = self.connect().execute(sql, params).fetchone()
        return dict(found) if found is not None else None

    def scalar(self, sql: str, params: Params = (), default: Any = None) -> Any:
        """Birinchi qatorning birinchi ustuni; bo'lmasa (yoki NULL) `default`."""
        found = self.connect().execute(sql, params).fetchone()
        if found is None or found[0] is None:
            return default
        return found[0]

    @contextlib.contextmanager
    def transaction(self) -> Iterator[sqlite3.Connection]:
        """`BEGIN IMMEDIATE ... COMMIT`; xatoda `ROLLBACK` va xato qaytadi.

        IMMEDIATE: yozuv qulfi BOSHIDA olinadi. Oddiy `BEGIN` da qulf
        birinchi yozuvda so'ralardi va o'rtada o'qigan ma'lumot eskirib
        qolishi mumkin edi ("oxirgi admin" tekshiruvi kabi joylar uchun
        muhim).
        """
        conn = self.connect()
        conn.execute("BEGIN IMMEDIATE")
        try:
            yield conn
        except BaseException:
            with contextlib.suppress(sqlite3.Error):
                conn.execute("ROLLBACK")
            raise
        try:
            conn.execute("COMMIT")
        except BaseException:
            # COMMIT ham yiqilishi mumkin (disk to'la - SQLITE_FULL, IOERR) va
            # SQLite bunda tranzaksiyani OCHIQ qoldirishi mumkin. Ulanish shu
            # ipniki va qayta ishlatiladi: ochiq qolsa yozuv qulfi ushlanib
            # turadi (yozuvchi ip va boshqa admin amallari "database is
            # locked"), shu ipdagi keyingi `BEGIN` esa abadiy xato beradi.
            with contextlib.suppress(sqlite3.Error):
                if conn.in_transaction:
                    conn.execute("ROLLBACK")
            raise

    def version(self) -> int:
        """Sxema versiyasi (`PRAGMA user_version`)."""
        return int(self.connect().execute("PRAGMA user_version").fetchone()[0])

    def size_bytes(self) -> int:
        """Diskdagi hajm: asosiy fayl + `-wal` + `-shm`."""
        total = 0
        for suffix in ("", "-wal", "-shm"):
            with contextlib.suppress(OSError):
                total += os.path.getsize(f"{self.path}{suffix}")
        return total


# --- umumiy nusxa ---------------------------------------------------------------

_db: Database | None = None
_db_lock = threading.Lock()


def get_db() -> Database:
    """Ilova bo'yicha BITTA ombor - kerak bo'lganda yaratiladi.

    Yo'l birinchi chaqiruvda sozlamadan olinadi. Import paytida emas:
    testlar `reset_for_tests` bilan vaqtinchalik faylga o'tkazishga
    ulgurishi kerak.
    """
    global _db
    found = _db
    if found is not None:
        return found
    with _db_lock:
        if _db is None:
            _db = Database(Path(setting("analytics_db_file", default_path())))
        return _db


def reset_for_tests(path: Path | str) -> Database:
    """Umumiy omborni `path` ga almashtiradi, eskisining ulanishlarini yopadi.

    Faqat ombor. Yozuvchi ipni ham almashtirish uchun paketning o'zidagi
    `analytics.reset_for_tests` ishlatiladi.
    """
    global _db
    with _db_lock:
        old, _db = _db, Database(path)
    if old is not None:
        old.close_all()
    return _db


def iter_chunks(items: Sequence[Any], size: int) -> Iterable[Sequence[Any]]:
    """Ro'yxatni `size` lik bo'laklarga bo'ladi (`IN (?, ?, ...)` uchun:
    SQLite bitta so'rovda cheklangan sonli parametr qabul qiladi)."""
    for start in range(0, len(items), size):
        yield items[start:start + size]
