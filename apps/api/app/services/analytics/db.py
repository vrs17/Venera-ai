_limited_at: dict[str, float] = {}
_limited_lock = threading.Lock()


def log_limited(key: str, message: str, *args: Any, exc_info: bool = False) -> None:
    """Xatoni jurnalga yozadi - bir `key` uchun DAQIQASIGA BIR MARTA.

    NEGA. Yozib olish har kadrda ishlaydi. Disk to'lsa yoki fayl buzilsa
    xato ham har kadrda takrorlanadi va jurnalni minglab bir xil qator bilan
    to'ldirib, haqiqiy muammoni ko'mib yuborardi.
    """
    now = time.monotonic()
    with _limited_lock:
        last = _limited_at.get(key)
        if last is not None and now - last < 60.0:
            return
        _limited_at[key] = now
    # Traceback bilan - `log.exception` darajasi (ERROR): bu kutilmagan nosozlik.
    log.log(logging.ERROR if exc_info else logging.WARNING, message, *args, exc_info=exc_info)


