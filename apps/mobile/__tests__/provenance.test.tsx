/** Xulosa ostidagi jim yozuv: qaysi model yozgani ("Tayyorladi: Barno Core"); server aytmasa - yo'q. */
import { act, render, screen } from '@testing-library/react-native';

import { engineLabel } from '@/features/meeting/provenance';
import { Provenance } from '@/features/meeting/SummaryView';
import { useSettings } from '@/features/settings/settingsStore';

describe('engineLabel', () => {
  it.each([
    [{ provider: 'v3', model: 'venera-core' }, 'Barno Core'],
    [{ provider: 'v3', model: null }, 'Barno Core'],
    [{ provider: 'openai', model: 'gpt-4.1-mini' }, 'GPT (gpt-4.1-mini)'],
    [{ provider: 'openai', model: null }, 'GPT'],
    [{ provider: 'ollama', model: 'gemma4:31b' }, 'Gemma'],
    [{ provider: 'ollama', model: null }, 'Gemma'],
    [{ provider: 'ollama', model: 'qwen3:32b' }, 'qwen3:32b'],
    [null, null],
    [undefined, null],
  ] as const)('%j -> %j', (g, out) => {
    expect(engineLabel(g)).toBe(out);
  });
});

describe('Provenance caption', () => {
  beforeEach(() => useSettings.setState({ uiLang: 'uz' }));

  it('uz/ru/en caption under the summary', async () => {
    const { rerender } = await render(<Provenance summary={{ generatedBy: { provider: 'v3', model: 'x' } }} />);
    expect(screen.getByTestId('summary-provenance')).toHaveTextContent('Tayyorladi: Barno Core');
    await rerender(<Provenance summary={{ generatedBy: { provider: 'openai', model: 'gpt-4.1-mini' } }} />);
    expect(screen.getByText('Tayyorladi: GPT (gpt-4.1-mini)')).toBeTruthy();
    await rerender(<Provenance summary={{ generatedBy: { provider: 'ollama', model: 'gemma4:31b' } }} />);
    expect(screen.getByText('Tayyorladi: Gemma')).toBeTruthy();
    await act(async () => useSettings.setState({ uiLang: 'ru' }));
    await rerender(<Provenance summary={{ generatedBy: { provider: 'v3', model: null } }} />);
    expect(screen.getByText('Подготовлено: Barno Core')).toBeTruthy();
    await act(async () => useSettings.setState({ uiLang: 'en' }));
    expect(screen.getByText('Generated by Barno Core')).toBeTruthy();
  });

  it('hidden when the server does not say (old summary / not ready)', async () => {
    await render(<Provenance summary={{ generatedBy: null }} />);
    expect(screen.queryByTestId('summary-provenance')).toBeNull();
  });
});
