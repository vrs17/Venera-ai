/**
 * Xulosa ostidagi BITTA jim qator: qaysi model yozgani ("Tayyorladi: Barno Core"), kayfiyat,
 * kalit so'zlar va faollik - avval alohida kartalar edi (egasi, 2026-10-15). Server aytmagan
 * qism - yo'q; hech narsa bo'lmasa qator ham yo'q.
 */
import { render, screen } from '@testing-library/react-native';

import type { Summary } from '@/api/types';
import { engineLabel } from '@/features/meeting/provenance';
import { summaryMetaParts } from '@/features/meeting/summaryModel';
import { SummaryMeta } from '@/features/meeting/SummaryView';
import { makeT } from '@/i18n';

import { summary } from './fixtures/server';

const uz = makeT('uz');

describe('engineLabel', () => {
  it.each([
    [{ provider: 'v3', model: 'venera-core' }, 'Barno Core'],
    [{ provider: 'v3', model: null }, 'Barno Core'],
    [{ provider: 'openai', model: 'gpt-4.1-mini' }, 'GPT (gpt-4.1-mini)'],
    [{ provider: 'openai', model: null }, 'GPT'],
    [{ provider: 'claude', model: 'claude-sonnet-5-5' }, 'Claude Sonnet 5.5'],
    [{ provider: 'claude', model: 'claude-opus-5-5-20261001' }, 'Claude Opus 5.5'],
    [{ provider: 'claude', model: null }, 'Claude'],
    [{ provider: 'claude', model: 'something-else' }, 'Claude'],
    [{ provider: 'ollama', model: 'gemma4:31b' }, 'Gemma'],
    [{ provider: 'ollama', model: null }, 'Gemma'],
    [{ provider: 'ollama', model: 'qwen3:32b' }, 'qwen3:32b'],
    [null, null],
    [undefined, null],
  ] as const)('%j -> %j', (g, out) => {
    expect(engineLabel(g)).toBe(out);
  });
});

describe('summary meta line', () => {
  const only = (generatedBy: Summary['generatedBy']) => ({ ...summary(), content: null, generatedBy });

  it('model caption in uz/ru/en; nothing when the server does not say', () => {
    expect(summaryMetaParts(only({ provider: 'v3', model: 'x' }), uz)).toEqual(['Tayyorladi: Barno Core']);
    expect(summaryMetaParts(only({ provider: 'openai', model: 'gpt-4.1-mini' }), uz)).toEqual(['Tayyorladi: GPT (gpt-4.1-mini)']);
    expect(summaryMetaParts(only({ provider: 'claude', model: 'claude-sonnet-5-5' }), uz)).toEqual(['Tayyorladi: Claude Sonnet 5.5']);
    expect(summaryMetaParts(only({ provider: 'ollama', model: 'gemma4:31b' }), uz)).toEqual(['Tayyorladi: Gemma']);
    expect(summaryMetaParts(only({ provider: 'v3', model: null }), makeT('ru'))).toEqual(['Подготовлено: Barno Core']);
    expect(summaryMetaParts(only({ provider: 'v3', model: null }), makeT('en'))).toEqual(['Generated by Barno Core']);
    expect(summaryMetaParts(only(null), uz)).toEqual([]);
  });

  it('folds tone, keywords and talk share into one line (merged speakers counted once)', () => {
    // S1 Aziz 58%, S2 nomsiz 42%; S3 S1 ga birlashtirilgan - ulushi Aziz'ga qo'shiladi.
    const s = summary();
    s.content!.participants = [...s.content!.participants, { speaker: 'S3', suggestedName: null, nameEvidence: [], role: null, talkSec: 30, talkShare: 0.03 }];
    expect(summaryMetaParts(s, uz)).toEqual([
      'Kayfiyat: ijobiy',
      "Kalit so'zlar: narx, hisobot",
      'Faollik: Aziz 61%, 2-ishtirokchi 42%',
      'Tayyorladi: Gemma',
    ]);
    // Bitta odamning ulushi ("100%") - ma'lumot emas; kayfiyat/kalit so'z yo'q - qism ham yo'q.
    s.content!.participants = [s.content!.participants[0]];
    s.content!.sentiment = null;
    s.content!.keywords = [];
    expect(summaryMetaParts(s, makeT('en'))).toEqual(['Generated by Gemma']);
  });

  it('renders the parts as one muted line, or nothing', async () => {
    const { rerender } = await render(<SummaryMeta parts={['Kayfiyat: neytral', 'Tayyorladi: Gemma']} />);
    expect(screen.getByTestId('summary-meta')).toHaveTextContent('Kayfiyat: neytral · Tayyorladi: Gemma');
    await rerender(<SummaryMeta parts={[]} />);
    expect(screen.queryByTestId('summary-meta')).toBeNull();
  });
});
