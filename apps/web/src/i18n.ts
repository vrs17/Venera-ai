// vue-i18n setup. The locale is persisted to localStorage and reflected as
// <html lang>; index.html sets <html lang> pre-paint to avoid a flash, and
// setLocale() keeps it in sync afterwards. Four locales: Uzbek (Latin,
// default), Uzbek (Cyrillic), Russian, English.
//
// English is the source of truth for the key set: each other dictionary is
// typed `Dict = Record<MsgKey, string>`, so adding a key to `en` forces every
// other locale to define it too (a compile error otherwise).

import { createI18n } from 'vue-i18n'
import type { ActorType } from './types'

export type Locale = 'uz' | 'uz-Cyrl' | 'ru' | 'en'

/** Display order + native labels for the language switcher. `htmlLang` is the
 *  BCP-47 tag written to <html lang> (helps screen readers and hyphenation). */
export const LOCALES: { code: Locale; label: string; htmlLang: string }[] = [
  { code: 'uz', label: 'Oʻzbek', htmlLang: 'uz-Latn' },
  { code: 'uz-Cyrl', label: 'Ўзбек', htmlLang: 'uz-Cyrl' },
  { code: 'ru', label: 'Русский', htmlLang: 'ru' },
  { code: 'en', label: 'English', htmlLang: 'en' },
]

const KEY = 'venera_locale'
const DEFAULT_LOCALE: Locale = 'uz'

function isLocale(v: unknown): v is Locale {
  return v === 'uz' || v === 'uz-Cyrl' || v === 'ru' || v === 'en'
}

export function getInitialLocale(): Locale {
  try {
    const saved = localStorage.getItem(KEY)
    if (isLocale(saved)) return saved
  } catch {
    /* localStorage unavailable */
  }
  return DEFAULT_LOCALE
}

export function applyLocale(locale: Locale): void {
  const meta = LOCALES.find((l) => l.code === locale) ?? LOCALES[0]
  document.documentElement.setAttribute('lang', meta.htmlLang)
  try {
    localStorage.setItem(KEY, locale)
  } catch {
    /* ignore */
  }
}

